/** Build RAG context string from retrieved services */
export function buildRAGContext(
  services: Record<string, unknown>[],
  intent: {
    query: string | null
    categories: string[] | null
    totalBudget: number | null
    participants: number | null
    location: string | null
  }
): string {
  const lines: string[] = []

  lines.push('## מידע שחולץ מהשיחה:')
  if (intent.categories && intent.categories.length > 0)
    lines.push(`- קטגוריות: ${intent.categories.join(', ')}`)
  if (intent.totalBudget) lines.push(`- תקציב כולל: ₪${intent.totalBudget.toLocaleString('he-IL')}`)
  if (intent.participants) lines.push(`- משתתפים: ${intent.participants}`)
  if (intent.totalBudget && intent.participants)
    lines.push(`- תקציב לאדם: ₪${Math.floor(intent.totalBudget / intent.participants).toLocaleString('he-IL')}`)
  if (intent.location) lines.push(`- מיקום: ${intent.location}`)
  if (intent.query) lines.push(`- חיפוש חופשי: ${intent.query}`)

  if (services.length === 0) {
    lines.push('\n## שירותים שנמצאו: לא נמצאו תוצאות ישירות')
    lines.push('**חובה:** אל תגיד "לא נמצאו תוצאות" ותעצור. חשוב על המטרה העמוקה של המשתמש ותמליץ על שירותים חלופיים מהמאגר שנותנים ערך דומה.')
    return lines.join('\n')
  }

  lines.push(`\n## שירותים שנמצאו (${services.length} תוצאות):`)

  const pricingUnitHe: Record<string, string> = {
    person: 'לאדם', group: 'לקבוצה', hour: 'לשעה',
    project: 'לפרויקט', month: 'לחודש', unit: 'ליחידה',
  }
  const locationHe: Record<string, string> = {
    onsite: 'במשרד', remote: 'מחוץ למשרד', both: 'גם וגם',
  }

  for (const svc of services.slice(0, 20)) {
    const priceStr = svc.price != null
      ? `₪${Number(svc.price).toLocaleString('he-IL')} ${pricingUnitHe[svc.pricing_unit as string] || ''}`
      : 'מחיר לא צוין'
    const partStr =
      svc.min_participants != null || svc.max_participants != null
        ? `${svc.min_participants ?? '?'}–${svc.max_participants ?? '?'} משתתפים`
        : 'כמות לא צוינה'
    const locStr = locationHe[svc.location_type as string] || 'לא צוין'

    lines.push(
      `- [${svc.id}] "${svc.service_name}" | ספק: ${svc.supplier_name} | קטגוריה: ${svc.category_primary}/${svc.category_secondary || '-'} | ${priceStr} | ${partStr} | מיקום: ${locStr}${svc.notes ? ` | הערות: ${(svc.notes as string).slice(0, 120)}` : ''}`
    )
  }

  return lines.join('\n')
}

